def main():
    conn = pymysql.connect(host='127.0.0.1', port=3306, user='root', password='123456',
                           database='flash_game_community', charset='utf8mb4')
    cur = conn.cursor()
    # 清空旧题（避免重复）
    cur.execute("DELETE FROM quiz_questions")
    total = 0
    for cat, qs in QUESTIONS.items():
        for i, (q, a, b, c, d, ans) in enumerate(qs, 1):
            cur.execute(
                "INSERT INTO quiz_questions (category, question, option_a, option_b, option_c, option_d, correct_answer, score, sort_order, status, created_at, updated_at) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,1,NOW(),NOW())",
                (cat, q, a, b, c, d, ans, 10, i))
            total += 1
    conn.commit()
    cur.close(); conn.close()
    print(f"inserted {total} questions")

if __name__ == '__main__':
    main()

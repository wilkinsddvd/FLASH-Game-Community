/* ── 查询辅助 ── */
import { canonicalKey } from './vehicle-name.js'

const VEHICLE_EN_BY_KEY = new Map()
for (const [zh, en] of Object.entries(VEHICLE_EN)) {
  const k = canonicalKey(zh)
  if (!VEHICLE_EN_BY_KEY.has(k)) VEHICLE_EN_BY_KEY.set(k, en)
}

export function vehicleEnName(name) {
  const raw = String(name || '')
  if (VEHICLE_EN[raw]) return VEHICLE_EN[raw]
  return VEHICLE_EN_BY_KEY.get(canonicalKey(raw)) || ''
}

export function factionEnName(code) {
  return FACTION_EN[String(code || '').toUpperCase()] || ''
}

export function rosterEnName(key) {
  return ROSTER_EN[String(key || '')] || ''
}

export function vehicleTypeEnName(zh) {
  return VEHICLE_TYPE_EN[String(zh || '')] || ''
}

export function rosterTypeEnName(zh) {
  return ROSTER_TYPE_EN[String(zh || '')] || ''
}

export function vehicleCatEnName(key) {
  return VEHICLE_CAT_EN[String(key || '')] || ''
}
